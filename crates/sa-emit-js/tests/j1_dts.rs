use sa_emit_js::dts::{dts_path_for_js_path, dts_type_name, emit_dts, DtsAliases};
use sa_ir::{CapPrefix, Function, FunctionKind, ParamSpec, PrimType, Program, Signature, SourceLoc};

fn signature(
    name: &str,
    params: &[(&str, PrimType)],
    ret: PrimType,
    fallible: bool,
) -> Signature {
    let mut sig = Signature::new(name);
    sig.kind = FunctionKind::Exported;
    sig.params = params
        .iter()
        .map(|(name, ty)| ParamSpec::new(*name, *ty, CapPrefix::ByValue))
        .collect();
    sig.return_ty = ret;
    sig.return_fallible = fallible;
    sig
}

fn program(sigs: Vec<Signature>) -> Program {
    let mut out = Program::new();
    for sig in sigs {
        out.functions.push(Function::new(sig, SourceLoc::unknown()));
    }
    out
}

#[test]
fn j1_type_mapping_table() {
    let mut aliases = DtsAliases::default();
    for ty in [
        PrimType::I1,
        PrimType::I8,
        PrimType::I16,
        PrimType::I32,
        PrimType::U8,
        PrimType::U16,
        PrimType::U32,
        PrimType::F32,
        PrimType::F64,
    ] {
        assert_eq!(dts_type_name(ty, &mut aliases), Some("number"));
    }
    assert_eq!(dts_type_name(PrimType::I64, &mut aliases), Some("SaI64"));
    assert_eq!(dts_type_name(PrimType::U64, &mut aliases), Some("SaU64"));
    assert_eq!(dts_type_name(PrimType::Ptr, &mut aliases), Some("SaPtr"));
    assert_eq!(
        dts_type_name(PrimType::BlobHandle, &mut aliases),
        Some("SaHandle")
    );
    assert!(aliases.sa_i64 && aliases.sa_u64 && aliases.sa_ptr && aliases.sa_handle);
    assert!(!aliases.sa_fallible);
    assert_eq!(dts_type_name(PrimType::V128, &mut aliases), None);
    assert_eq!(dts_type_name(PrimType::Void, &mut aliases), None);
}

#[test]
fn j1_dts_path_derivation() {
    for (js, dts) in [
        ("foo.js", "foo.d.ts"),
        ("foo.mjs", "foo.d.ts"),
        ("foo.cjs", "foo.d.ts"),
        ("foo", "foo.d.ts"),
        ("dir.x/foo.js", "dir.x/foo.d.ts"),
        ("out/foo.min.js", "out/foo.min.d.ts"),
    ] {
        assert_eq!(dts_path_for_js_path(js), dts, "js={js}");
    }
}

#[test]
fn j1_decl_shapes_follow_measured_boundary() {
    let p = program(vec![
        signature("id_i32", &[("x", PrimType::I32)], PrimType::I32, false),
        signature("id_i64", &[("x", PrimType::I64)], PrimType::I64, false),
        signature("id_ptr", &[("x", PrimType::Ptr)], PrimType::Ptr, false),
        signature(
            "pair_len",
            &[("p", PrimType::Ptr), ("len", PrimType::U64)],
            PrimType::U64,
            false,
        ),
        signature("noop", &[], PrimType::Void, false),
        signature("fall_ok", &[("x", PrimType::I32)], PrimType::I32, true),
        signature("fall_void", &[], PrimType::Void, true),
    ]);
    let dts = emit_dts(&p, "probe.sa").expect("emission must succeed");
    for needle in [
        "// Generated by `sa build-js --emit-dts` from probe.sa. Do not edit.",
        "export type SaI64 = number | bigint;",
        "export type SaU64 = number | bigint;",
        "export type SaPtr = number | bigint;",
        "export type SaFallible<T> = { s: number; v: T };",
        "export declare function id_i32(x: number): number;",
        "export declare function id_i64(x: SaI64): SaI64;",
        "export declare function id_ptr(x: SaPtr): SaPtr;",
        "export declare function pair_len(p: SaPtr, len: SaU64): SaU64;",
        "export declare function noop(): number;",
        "export declare function fall_ok(x: number): SaFallible<number>;",
        "export declare function fall_void(): { s: number };",
    ] {
        assert!(dts.contains(needle), "missing: {needle}");
    }
    assert!(!dts.contains("SaHandle"));
    assert!(!dts.contains("any"));
}

#[test]
fn j1_duplicate_js_names_collapse_to_last_signature() {
    let p = program(vec![
        signature("foo-bar", &[], PrimType::I32, false),
        signature("foo.bar", &[], PrimType::I64, false),
    ]);
    let dts = emit_dts(&p, "dup.sa").expect("emission must succeed");
    assert_eq!(dts.matches("export declare function foo_bar(").count(), 1);
    assert!(dts.contains("export declare function foo_bar(): SaI64;"));
    assert_eq!(emit_dts(&p, "dup.sa").unwrap(), dts);
}

#[test]
fn j1_unsupported_v128_fails_loudly() {
    let param = program(vec![signature(
        "bad_param",
        &[("v", PrimType::V128)],
        PrimType::I32,
        false,
    )]);
    let errs = emit_dts(&param, "v.sa").expect_err("v128 param must be rejected");
    assert_eq!(errs.len(), 1);
    assert_eq!(
        errs[0].message,
        "v128 parameter has no JS representation (--emit-dts)"
    );
    assert_eq!(errs[0].function.as_deref(), Some("bad_param"));

    let ret = program(vec![signature(
        "bad_ret",
        &[],
        PrimType::V128,
        false,
    )]);
    let errs = emit_dts(&ret, "v.sa").expect_err("v128 return must be rejected");
    assert_eq!(
        errs[0].message,
        "v128 return has no JS representation (--emit-dts)"
    );
    assert_eq!(errs[0].function.as_deref(), Some("bad_ret"));
}

#[test]
fn j1_aliases_only_when_used() {
    let p = program(vec![signature("only", &[("x", PrimType::I32)], PrimType::I32, false)]);
    let dts = emit_dts(&p, "small.sa").expect("emission must succeed");
    assert!(!dts.contains("export type"));
    assert!(dts.contains("export declare function only(x: number): number;"));
}
