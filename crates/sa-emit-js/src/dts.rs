use crate::ident::{js_func_name, js_ident};
use sa_ir::{Diagnostic, PrimType, Program, Signature, SourceLoc, Trap};
use std::collections::HashMap;

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct DtsAliases {
    pub sa_i64: bool,
    pub sa_u64: bool,
    pub sa_ptr: bool,
    pub sa_handle: bool,
    pub sa_fallible: bool,
}

pub fn dts_type_name(ty: PrimType, aliases: &mut DtsAliases) -> Option<&'static str> {
    match ty {
        PrimType::I1
        | PrimType::I8
        | PrimType::I16
        | PrimType::I32
        | PrimType::U8
        | PrimType::U16
        | PrimType::U32
        | PrimType::F32
        | PrimType::F64 => Some("number"),
        PrimType::I64 => {
            aliases.sa_i64 = true;
            Some("SaI64")
        }
        PrimType::U64 => {
            aliases.sa_u64 = true;
            Some("SaU64")
        }
        PrimType::Ptr => {
            aliases.sa_ptr = true;
            Some("SaPtr")
        }
        PrimType::BlobHandle => {
            aliases.sa_handle = true;
            Some("SaHandle")
        }
        PrimType::Void | PrimType::V128 => None,
    }
}

fn unsupported(slot: &str, ty: &str, func: &str) -> Vec<Diagnostic> {
    vec![Diagnostic::new(
        Trap::UnsupportedType,
        format!("{ty} {slot} has no JS representation (--emit-dts)"),
        SourceLoc::unknown(),
    )
    .in_function(func)
    .with_hint("the JS backend has no representation for this type on the export surface")]
}

fn dts_return_type(
    sig: &Signature,
    aliases: &mut DtsAliases,
) -> Result<String, Vec<Diagnostic>> {
    if sig.return_fallible {
        if sig.return_ty == PrimType::Void {
            return Ok("{ s: number }".to_string());
        }
        let inner = match dts_type_name(sig.return_ty, aliases) {
            Some(name) => name,
            None => return Err(unsupported("return", sig.return_ty.name(), &sig.name)),
        };
        aliases.sa_fallible = true;
        return Ok(format!("SaFallible<{inner}>"));
    }
    if sig.return_ty == PrimType::Void {
        return Ok("number".to_string());
    }
    match dts_type_name(sig.return_ty, aliases) {
        Some(name) => Ok(name.to_string()),
        None => Err(unsupported("return", sig.return_ty.name(), &sig.name)),
    }
}

fn dts_decl(sig: &Signature, aliases: &mut DtsAliases) -> Result<String, Vec<Diagnostic>> {
    for param in &sig.params {
        if param.ty == PrimType::V128 || param.ty == PrimType::Void {
            return Err(unsupported("parameter", param.ty.name(), &sig.name));
        }
    }
    if sig.return_ty == PrimType::V128 {
        return Err(unsupported("return", "v128", &sig.name));
    }
    let ret = dts_return_type(sig, aliases)?;
    let mut out = String::from("export declare function ");
    out.push_str(&js_func_name(&sig.name));
    out.push('(');
    for (index, param) in sig.params.iter().enumerate() {
        if index != 0 {
            out.push_str(", ");
        }
        out.push_str(&js_ident(&param.name));
        out.push_str(": ");
        match dts_type_name(param.ty, aliases) {
            Some(name) => out.push_str(name),
            None => return Err(unsupported("parameter", param.ty.name(), &sig.name)),
        }
    }
    out.push_str("): ");
    out.push_str(&ret);
    out.push_str(";\n");
    Ok(out)
}

pub fn emit_dts(program: &Program, source_path: &str) -> Result<String, Vec<Diagnostic>> {
    let mut aliases = DtsAliases::default();
    let mut order: Vec<String> = Vec::new();
    let mut decls: HashMap<String, String> = HashMap::new();
    for function in &program.functions {
        let decl = dts_decl(&function.sig, &mut aliases)?;
        let name = js_func_name(&function.sig.name);
        if !decls.contains_key(&name) {
            order.push(name.clone());
        }
        decls.insert(name, decl);
    }
    let mut out = String::new();
    out.push_str(&format!(
        "// Generated by `sa build-js --emit-dts` from {source_path}. Do not edit.\n"
    ));
    out.push_str("// SA void functions return 0 in the JS backend; i64/u64/ptr/handle\n");
    out.push_str("// values are `number | bigint` (measured, see DTS_EMIT_DESIGN.md).\n");
    if aliases.sa_i64 {
        out.push_str("export type SaI64 = number | bigint;\n");
    }
    if aliases.sa_u64 {
        out.push_str("export type SaU64 = number | bigint;\n");
    }
    if aliases.sa_ptr {
        out.push_str("export type SaPtr = number | bigint;\n");
    }
    if aliases.sa_handle {
        out.push_str("export type SaHandle = number | bigint;\n");
    }
    if aliases.sa_fallible {
        out.push_str("export type SaFallible<T> = { s: number; v: T }; // v is meaningful only when s === 0\n");
    }
    for name in &order {
        out.push_str(&decls[name]);
    }
    Ok(out)
}

pub fn dts_path_for_js_path(js_path: &str) -> String {
    let base_start = js_path.rfind('/').map(|index| index + 1).unwrap_or(0);
    let base = &js_path[base_start..];
    let stem_end = base
        .rfind('.')
        .filter(|index| *index > 0)
        .map(|index| base_start + index)
        .unwrap_or(js_path.len());
    format!("{}.d.ts", &js_path[..stem_end])
}
